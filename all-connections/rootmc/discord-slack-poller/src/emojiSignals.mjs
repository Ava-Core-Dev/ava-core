/** Strip skin-tone modifiers + variation selectors for lookup. */
export function normalizeEmojiKey(raw) {
  return String(raw || "")
    .trim()
    .replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "")
    .replace(/\uFE0F/g, "");
}

export function lookupStandardSignal(emoji) {
  const raw = String(emoji || "").trim();
  if (!raw) return null;
  if (STANDARD_EMOJI_SIGNALS[raw]) return STANDARD_EMOJI_SIGNALS[raw];
  const norm = normalizeEmojiKey(raw);
  if (STANDARD_EMOJI_SIGNALS[norm]) return STANDARD_EMOJI_SIGNALS[norm];
  // try with VS16 re-added for some keys
  if (STANDARD_EMOJI_SIGNALS[`${norm}\uFE0F`]) return STANDARD_EMOJI_SIGNALS[`${norm}\uFE0F`];
  return null;
}
