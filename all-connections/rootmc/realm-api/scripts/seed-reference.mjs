#!/usr/bin/env node
/**
 * Generate 0083_rootmc_reference_seed.sql from canonical reference JSON.
 *
 * Usage (from rootmc-realm-api/):
 *   node scripts/seed-reference.mjs
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { D1_MIGRATIONS_DIR, REFERENCE_DIR } from "./lib/rootmc-paths.mjs";

const VERSION = "grahamedgecombe-legacy-full";
const CATEGORIES = ["blocks", "items", "mobs", "enchantments", "potions", "trades"];
const now = new Date().toISOString();
const outFile = path.join(D1_MIGRATIONS_DIR, "0083_rootmc_reference_seed.sql");

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

const lines = [
  "-- Auto-generated by rootmc-realm-api/scripts/seed-reference.mjs — do not hand-edit.",
  `-- version: ${VERSION}`,
  "",
  `INSERT OR REPLACE INTO rootmc_reference_meta (id, version, updated_at)`,
  `VALUES (1, '${sqlEscape(VERSION)}', '${now}');`,
  "",
];

for (const category of CATEGORIES) {
  const filePath = path.join(REFERENCE_DIR, `${category}.json`);
  if (!fs.existsSync(filePath)) {
    console.error(`Missing ${filePath}`);
    process.exit(1);
  }
  const json = fs.readFileSync(filePath, "utf8");
  const sha = crypto.createHash("sha256").update(json).digest("hex");
  const byteSize = Buffer.byteLength(json, "utf8");
  lines.push(
    `INSERT OR REPLACE INTO rootmc_reference_bundle`,
    `(category, json_blob, byte_size, content_sha256, updated_at)`,
    `VALUES ('${category}', '${sqlEscape(json)}', ${byteSize}, '${sha}', '${now}');`,
    "",
  );
}

fs.writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Wrote ${outFile} (${CATEGORIES.length} categories, version ${VERSION})`);
